def to_sarif(result: ScanResult) -> str:
    """Generate SARIF report for GitHub Code Scanning integration."""
    sarif = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": "TechAccess",
                    "version": "0.1.0",
                    "informationUri": "https://github.com/sophiacave/techaccess",
                    "rules": [],
                }
            },
            "results": [],
        }],
    }

    run = sarif["runs"][0]
    seen_rules: set[str] = set()

    for issue in result.issues:
        if issue.rule_id not in seen_rules:
            seen_rules.add(issue.rule_id)
            run["tool"]["driver"]["rules"].append({
                "id": issue.rule_id,
                "shortDescription": {"text": issue.description},
                "helpUri": issue.help_url or "",
                "properties": {"wcag": issue.wcag} if issue.wcag else {},
            })

        level_map = {"critical": "error", "serious": "error", "moderate": "warning", "minor": "note"}
        run["results"].append({
            "ruleId": issue.rule_id,
            "level": level_map.get(issue.impact, "warning"),
            "message": {"text": f"{issue.description} ({issue.viewport})"},
            "locations": [{
                "physicalLocation": {
                    "artifactLocation": {"uri": result.url},
                    "region": {"snippet": {"text": issue.element_html[:200] if issue.element_html else ""}},
                }
            }],
        })

    return json.dumps(sarif, indent=2)
